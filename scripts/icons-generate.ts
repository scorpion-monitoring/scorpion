// `pnpm icons:generate [--check]`: writes `packages/contracts/src/icons.ts`, the closed table of the icons the app
// draws, from the outline icons of Tabler (https://tabler.io/icons, MIT, see THIRD_PARTY_NOTICES.md). `@tabler/icons`
// is a development dependency only: the table holds the path data, so nothing of the package ships. With `--check`
// nothing is written and the exit code says whether the committed file is what the script would write (`pnpm check`).
//
// To add an icon: add its name and the Tabler name below, run `pnpm icons:generate`, commit both files. To change
// which Tabler icon a name shows, change the right-hand side. A name that is not here shows the dot.
