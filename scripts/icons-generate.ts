const root = resolve(import.meta.dirname, '..');
const output = join(root, 'packages/contracts/src/icons.ts');

/** The path data of one outline icon: every `d` of its `<path>` elements but the invisible bounding box, joined. */
export function pathData(svg: string, name: string): string {
  const shapes = svg.match(/<(circle|rect|ellipse|line|polyline|polygon)\b/g);
  if (shapes)
    throw new Error(`${name}: the icon has a ${shapes[0].slice(1)}; convert it to a path first`);
  const data = [...svg.matchAll(/<path\b([^>]*)>/g)]
    .filter(([, attributes]) => !/stroke="none"/.test(attributes!))
    .map(([, attributes]) => /\bd="([^"]+)"/.exec(attributes!)?.[1]?.trim())
    .filter((d): d is string => d !== undefined && d !== '');
  if (data.length === 0) throw new Error(`${name}: no path found`);
  return data.join(' ');
}

export function render(read: (file: string) => string): string {
  const lines = Object.entries(ICONS).map(([name, file]) => {
    const d = pathData(read(file), `${name} (${file})`);
    return `  ${name}: '${d}',`;
  });
  return `// GENERATED by \`pnpm icons:generate\` from the outline icons of Tabler (https://tabler.io/icons, MIT licence, see
// THIRD_PARTY_NOTICES.md). Do not edit; change \`scripts/icons-generate.ts\` and regenerate. \`pnpm check\` fails on a diff.
//
// The outline icons of the shell, drawn on a 24 x 24 grid: the table the web app's \`Icon.svelte\` reads and the
// navigation test of the server checks against the \`ui.nav\` entries. The table is closed: a name that is not here
// shows a dot, so a typo in a registry entry cannot break a page.
export const iconShapes: Record<string, string> = {
${lines.join('\n')}
};
`;
}

function main() {
  // The package restricts its `exports`; the files are read from where pnpm links it.
  const dir = join(root, 'node_modules/@tabler/icons/icons/outline');
  const text = render((file) => readFileSync(join(dir, `${file}.svg`), 'utf8'));
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(output, 'utf8');
    } catch {
      /* missing: differs */
    }
    if (current !== text) {
      console.error(
        'packages/contracts/src/icons.ts differs from what `pnpm icons:generate` writes. Run it and commit the result.',
      );
      process.exit(1);
    }
    return;
  }
  writeFileSync(output, text);
  console.log(`wrote ${output} (${Object.keys(ICONS).length} icons)`);
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) main();
