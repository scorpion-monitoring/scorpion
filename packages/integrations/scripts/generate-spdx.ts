// `node packages/integrations/scripts/generate-spdx.ts`: writes src/spdx-bundled.generated.ts from the
// SPDX license-list-data release named in src/spdx-pin.ts. Run it when the pin changes (a test fails
// while the bundled copy is older than the pin). The bundled list is the fallback when the live list
// and the cache are both unavailable, so it holds only what the adapter returns.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { normaliseSpdxList } from '../src/spdx.ts';
import { SPDX_PINNED_RELEASE } from '../src/spdx-pin.ts';

const url = `https://raw.githubusercontent.com/spdx/license-list-data/v${SPDX_PINNED_RELEASE}/json/licenses.json`;
const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
const list = normaliseSpdxList(await response.json());
if (!list || list.version !== SPDX_PINNED_RELEASE) {
  throw new Error(`${url}: the file is not the pinned release ${SPDX_PINNED_RELEASE}`);
}
const rows = list.licenses.map((l) => [l.id, l.name, l.osiApproved ? 1 : 0, l.deprecated ? 1 : 0]);
const out = `// GENERATED by packages/integrations/scripts/generate-spdx.ts from SPDX license list ${list.version}. Do not edit.
// The fallback copy of the SPDX list: [id, name, osiApproved (0 or 1), deprecated (0 or 1)].
export const BUNDLED_SPDX_VERSION = ${JSON.stringify(list.version)};
export const BUNDLED_SPDX_ROWS: readonly (readonly [string, string, 0 | 1, 0 | 1])[] = ${JSON.stringify(rows)};
`;
writeFileSync(join(import.meta.dirname, '../src/spdx-bundled.generated.ts'), out);
console.log(`wrote ${rows.length} licences of SPDX ${list.version}`);
